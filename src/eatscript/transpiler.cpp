#include "eatsbits/eatscript/transpiler.hpp"
#include "eatsbits/eatscript/lexer.hpp"
#include "eatsbits/eatscript/parser.hpp"
#include <sstream>

namespace eatsbits::eatscript {

std::string Transpiler::emitIndent() const {
    return std::string(indentLevel_ * 4, ' ');
}

std::string Transpiler::transpileSource(const std::string& source, const std::string& pluginId,
                                        const std::string& pluginName) {
    Lexer lexer(source);
    auto tokens = lexer.tokenize();
    Parser parser(std::move(tokens));
    auto prog = parser.parse();
    if (!prog) return "// Parsing failed\n";
    return transpile(*prog, pluginId, pluginName);
}

std::string Transpiler::transpile(const Program& program, const std::string& pluginId,
                                  const std::string& pluginName) {
    processBodyCode_.clear();

    // Scan for process function
    for (const auto& stmt : program.statements) {
        auto* func = ast_cast<FunctionDef>(stmt.get());
        if (func && func->name == "process") {
            inProcessFunction_ = true;
            indentLevel_ = 2;
            for (const auto& s : func->body) {
                transpileStmt(s.get());
            }
            inProcessFunction_ = false;
        }
    }

    std::ostringstream ss;
    ss << "// Generated by Eatsbits Eatscript AOT Transpiler\n";
    ss << "#include \"eatsbits/abi/eats_plugin_abi.h\"\n";
    ss << "#include <cmath>\n";
    ss << "#include <numbers>\n";
    ss << "#include <algorithm>\n\n";

    ss << "struct PluginInstance_" << pluginId << " {\n";
    ss << "    double sampleRate{48000.0};\n";
    ss << "    float params[16]{};\n";
    ss << "    double currentFreq{440.0};\n";
    ss << "    uint8_t currentNote{69};\n";
    ss << "    uint64_t sampleCount{0};\n";
    ss << "    bool active{false};\n";
    ss << "};\n\n";

    ss << "extern \"C\" {\n\n";

    // create_instance
    ss << "static void* create_instance_" << pluginId << "(double sampleRate) {\n";
    ss << "    auto* inst = new PluginInstance_" << pluginId << "();\n";
    ss << "    inst->sampleRate = sampleRate;\n";
    ss << "    return inst;\n";
    ss << "}\n\n";

    // destroy_instance
    ss << "static void destroy_instance_" << pluginId << "(void* instance) {\n";
    ss << "    delete static_cast<PluginInstance_" << pluginId << "*>(instance);\n";
    ss << "}\n\n";

    // set_param
    ss << "static void set_param_" << pluginId << "(void* instance, uint32_t paramId, float value) {\n";
    ss << "    auto* inst = static_cast<PluginInstance_" << pluginId << "*>(instance);\n";
    ss << "    if (paramId < 16) inst->params[paramId] = value;\n";
    ss << "}\n\n";

    // note_on
    ss << "static void note_on_" << pluginId << "(void* instance, uint8_t pitch, float velocity) {\n";
    ss << "    auto* inst = static_cast<PluginInstance_" << pluginId << "*>(instance);\n";
    ss << "    inst->currentNote = pitch;\n";
    ss << "    inst->currentFreq = 440.0 * std::pow(2.0, (static_cast<double>(pitch) - 69.0) / 12.0);\n";
    ss << "    inst->sampleCount = 0;\n";
    ss << "    inst->active = true;\n";
    ss << "}\n\n";

    // note_off
    ss << "static void note_off_" << pluginId << "(void* instance, uint8_t pitch) {\n";
    ss << "    auto* inst = static_cast<PluginInstance_" << pluginId << "*>(instance);\n";
    ss << "    if (inst->currentNote == pitch) inst->active = false;\n";
    ss << "}\n\n";

    // process
    ss << "static void process_" << pluginId << "(void* instance, const EatsAudioBuffer* buffer) {\n";
    ss << "    auto* inst = static_cast<PluginInstance_" << pluginId << "*>(instance);\n";
    ss << "    if (!inst->active) return;\n";
    ss << "    float* outL = buffer->outputs[0];\n";
    ss << "    float* outR = (buffer->numChannels > 1) ? buffer->outputs[1] : outL;\n";
    ss << "    const double freq = inst->currentFreq;\n";
    ss << "    const double note = static_cast<double>(inst->currentNote);\n";
    ss << "    const double sampleRate = inst->sampleRate;\n\n";

    ss << "    for (uint32_t i = 0; i < buffer->numSamples; ++i) {\n";
    ss << "        const double time = static_cast<double>(inst->sampleCount++) / sampleRate;\n";
    ss << "        double sample = 0.0;\n";
    ss << processBodyCode_;
    ss << "        outL[i] += static_cast<float>(sample);\n";
    ss << "        outR[i] += static_cast<float>(sample);\n";
    ss << "    }\n";
    ss << "}\n\n";

    // Plugin Descriptor
    ss << "const EatsPluginDescriptor g_plugin_" << pluginId << " = {\n";
    ss << "    \"" << pluginId << "\",\n";
    ss << "    \"" << pluginName << "\",\n";
    ss << "    16,\n";
    ss << "    create_instance_" << pluginId << ",\n";
    ss << "    destroy_instance_" << pluginId << ",\n";
    ss << "    process_" << pluginId << ",\n";
    ss << "    set_param_" << pluginId << ",\n";
    ss << "    note_on_" << pluginId << ",\n";
    ss << "    note_off_" << pluginId << "\n";
    ss << "};\n\n";

    ss << "} // extern \"C\"\n";

    return ss.str();
}

void Transpiler::transpileStmt(const Stmt* stmt) {
    if (!stmt) return;
    switch (stmt->kind) {
        case StmtKind::Expr:
            visit(static_cast<ExprStmt*>(const_cast<Stmt*>(stmt)));
            break;
        case StmtKind::Assign:
            visit(static_cast<AssignStmt*>(const_cast<Stmt*>(stmt)));
            break;
        case StmtKind::Return:
            visit(static_cast<ReturnStmt*>(const_cast<Stmt*>(stmt)));
            break;
        case StmtKind::If:
            visit(static_cast<IfStmt*>(const_cast<Stmt*>(stmt)));
            break;
        case StmtKind::FunctionDef:
            visit(static_cast<FunctionDef*>(const_cast<Stmt*>(stmt)));
            break;
    }
}

void Transpiler::transpileExpr(const Expr* expr) {
    if (!expr) return;
    switch (expr->kind) {
        case ExprKind::Number:
            visit(static_cast<NumberLiteral*>(const_cast<Expr*>(expr)));
            break;
        case ExprKind::String:
            visit(static_cast<StringLiteral*>(const_cast<Expr*>(expr)));
            break;
        case ExprKind::Boolean:
            visit(static_cast<BooleanLiteral*>(const_cast<Expr*>(expr)));
            break;
        case ExprKind::Identifier:
            visit(static_cast<IdentifierExpr*>(const_cast<Expr*>(expr)));
            break;
        case ExprKind::Member:
            visit(static_cast<MemberExpr*>(const_cast<Expr*>(expr)));
            break;
        case ExprKind::Binary:
            visit(static_cast<BinaryExpr*>(const_cast<Expr*>(expr)));
            break;
        case ExprKind::Unary:
            visit(static_cast<UnaryExpr*>(const_cast<Expr*>(expr)));
            break;
        case ExprKind::Call:
            visit(static_cast<CallExpr*>(const_cast<Expr*>(expr)));
            break;
        case ExprKind::List:
            visit(static_cast<ListLiteral*>(const_cast<Expr*>(expr)));
            break;
        case ExprKind::Dict:
            visit(static_cast<DictLiteral*>(const_cast<Expr*>(expr)));
            break;
    }
}

void Transpiler::visit(NumberLiteral* node) {
    output_ += std::to_string(node->value);
}

void Transpiler::visit(StringLiteral* node) {
    output_ += "\"" + node->value + "\"";
}

void Transpiler::visit(BooleanLiteral* node) {
    output_ += node->value ? "true" : "false";
}

void Transpiler::visit(IdentifierExpr* node) {
    if (node->name == "pi") {
        output_ += "std::numbers::pi_v<double>";
    } else {
        output_ += node->name;
    }
}

void Transpiler::visit(MemberExpr* node) {
    auto* objId = ast_cast<IdentifierExpr>(node->object.get());
    if (objId && objId->name == "math" && node->member == "pi") {
        output_ += "std::numbers::pi_v<double>";
    } else {
        transpileExpr(node->object.get());
        output_ += "." + node->member;
    }
}

void Transpiler::visit(BinaryExpr* node) {
    output_ += "(";
    transpileExpr(node->left.get());
    switch (node->op) {
        case TokenType::Plus: output_ += " + "; break;
        case TokenType::Minus: output_ += " - "; break;
        case TokenType::Multiply: output_ += " * "; break;
        case TokenType::Divide: output_ += " / "; break;
        case TokenType::Power:
            // Rewrite a ** b as std::pow(a, b)
            output_ = "std::pow(" + output_;
            transpileExpr(node->right.get());
            output_ += ")";
            return;
        default: output_ += " + "; break;
    }
    transpileExpr(node->right.get());
    output_ += ")";
}

void Transpiler::visit(UnaryExpr* node) {
    if (node->op == TokenType::Minus) output_ += "-";
    transpileExpr(node->operand.get());
}

void Transpiler::visit(CallExpr* node) {
    auto* mem = ast_cast<MemberExpr>(node->callee.get());
    if (mem) {
        auto* objId = ast_cast<IdentifierExpr>(mem->object.get());
        if (objId && objId->name == "math") {
            output_ += "std::" + mem->member + "(";
            for (size_t i = 0; i < node->args.size(); ++i) {
                if (i > 0) output_ += ", ";
                transpileExpr(node->args[i].get());
            }
            output_ += ")";
            return;
        } else if (objId && objId->name == "params" && mem->member == "get") {
            output_ += "inst->params[0]";
            return;
        }
    }

    transpileExpr(node->callee.get());
    output_ += "(";
    for (size_t i = 0; i < node->args.size(); ++i) {
        if (i > 0) output_ += ", ";
        transpileExpr(node->args[i].get());
    }
    output_ += ")";
}

void Transpiler::visit(ListLiteral* node) {
    if (!node->elements.empty()) {
        transpileExpr(node->elements[0].get());
    }
}

void Transpiler::visit(DictLiteral* /*node*/) {}

void Transpiler::visit(ExprStmt* node) {
    output_.clear();
    transpileExpr(node->expression.get());
    processBodyCode_ += emitIndent() + output_ + ";\n";
}

void Transpiler::visit(AssignStmt* node) {
    output_.clear();
    transpileExpr(node->value.get());
    processBodyCode_ += emitIndent() + "double " + node->variableName + " = " + output_ + ";\n";
}

void Transpiler::visit(ReturnStmt* node) {
    output_.clear();
    if (node->value) {
        transpileExpr(node->value.get());
        processBodyCode_ += emitIndent() + "sample = " + output_ + ";\n";
    }
}

void Transpiler::visit(IfStmt* node) {
    output_.clear();
    transpileExpr(node->condition.get());
    processBodyCode_ += emitIndent() + "if (" + output_ + ") {\n";
    indentLevel_++;
    for (const auto& s : node->thenBranch) {
        transpileStmt(s.get());
    }
    indentLevel_--;
    processBodyCode_ += emitIndent() + "}\n";
}

void Transpiler::visit(FunctionDef* /*node*/) {}

} // namespace eatsbits::eatscript
